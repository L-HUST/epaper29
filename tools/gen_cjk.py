#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the small Chinese UI font used by the firmware.

The source font is Noto Sans SC (SIL Open Font License 1.1).  Only the
characters used by the device UI are embedded, as 1-bit bitmaps.

Run:
    .venv\\Scripts\\python.exe tools\\gen_cjk.py
"""

import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
FONT = os.environ.get("CJK_FONT", r"C:\Windows\Fonts\NotoSansSC-VF.ttf")
OUT = os.path.join(ROOT, "firmware", "include", "font_cjk.h")

# Every non-ASCII character used by the UI.  Add a character here and rerun.
CHARS = (
    "菜单阅读设置跳转页面全刷返回书库确定选择电源休眠打开取消上下改数字"
    "换位长按当前共页本刷新间隔时间关闭分钟第没有请用传书深按任意键唤醒修数据线度"
)


def glyphs(size):
    font = ImageFont.truetype(FONT, size)
    try:
        font.set_variation_by_name("Regular")
    except Exception:
        pass
    out = []
    for ch in sorted(set(CHARS)):
        bbox = font.getbbox(ch)
        cell = Image.new("1", (size, size), 0)
        d = ImageDraw.Draw(cell)
        d.text((-bbox[0], -bbox[1]), ch, font=font, fill=1)
        stride = (size + 7) // 8
        raw = cell.tobytes()
        rows = []
        for y in range(size):
            rows.append(raw[y * stride:(y + 1) * stride])
        out.append((ord(ch), b"".join(rows)))
    return out


def emit(f, name, size, items):
    stride = (size + 7) // 8
    f.write(f"#define {name}_W {size}\n")
    f.write(f"#define {name}_H {size}\n")
    f.write(f"#define {name}_STRIDE {stride}\n")
    f.write(f"static const CjkGlyph {name}_INDEX[] = {{\n")
    off = 0
    for cp, data in items:
        f.write("    {0x%04X, %u},\n" % (cp, off))
        off += len(data)
    f.write("};\n")
    f.write(f"static const uint8_t {name}_BITS[] = {{\n    ")
    col = 0
    for _, data in items:
        for b in data:
            f.write("0x%02X," % b)
            col += 1
            if col == 16:
                f.write("\n    ")
                col = 0
    f.write("\n};\n\n")


def main():
    a = glyphs(15)
    b = glyphs(12)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_cjk.py -- do not edit.\n")
        f.write("// Source: Noto Sans SC, SIL Open Font License 1.1.\n")
        f.write("// UI only subset; 1 = ink, 0 = paper.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct CjkGlyph { uint32_t cp; uint16_t off; };\n\n")
        emit(f, "CJK15", 15, a)
        emit(f, "CJK12", 12, b)
    print("wrote", OUT, "glyphs", len(a), len(b))


if __name__ == "__main__":
    main()
